test("Python excludes structurally proven noninstallable SDIST placeholders, not ordinary mention of sdist", () => {
  const values = parseMetadata([
    { path: "placeholder.py", kind: "setup", text: 'import sys\nfrom setuptools import setup\nif "sdist" in sys.argv:\n setup(name="azure-storage")\nelse:\n raise RuntimeError("deprecated")' },
    { path: "runtime.py", kind: "setup", text: 'from setuptools import setup\n# Supports sdist and wheels.\nsetup(name="azure-demo",packages=["azure_demo"])' },
    { path: "conditional.py", kind: "setup", text: 'from setuptools import setup\nif "sdist" in choices:\n setup(name="azure-demo")\nelse:\n raise RuntimeError("other mode")' },
  ]);
  assert.equal(object(values.get("placeholder.py"), "placeholder").sdist_only, true);
  assert.equal(object(values.get("runtime.py"), "runtime").sdist_only, false);
  assert.equal(object(values.get("conditional.py"), "conditional").sdist_only, false);
});
