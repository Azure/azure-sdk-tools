test("whole-file generator provenance uses leading comments, never Java symbols or member annotations", () => {
  assert.equal(generatorHeader(generated, "java"), true);
  assert.equal(generatorHeader("/* Copyright\n * Code generated by Microsoft (R) TypeSpec Code Generator.\n */\nclass X{}", "java"), true);
  for (const text of [
    "package p; import com.azure.core.annotation.Generated;\nclass X { @Generated String field; }",
    "/** Generator marker annotation. */\npublic @interface Generated {}",
    'class X { String text = "Code generated by Microsoft (R) AutoRest Code Generator."; }',
    "// Microsoft copyright. implementation model.\nclass GeneratedModelImpl {}",
  ]) assert.equal(generatorHeader(text, "java"), false);
  assert.equal(generatorHeader(pythonGenerated, "python"), true);
  assert.equal(generatorHeader('message = "Code generated by Microsoft (R) Python Code Generator."', "python"), false);
});
