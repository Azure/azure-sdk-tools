test("Java supports inherited source declarations, genuine empty starter jars and category exceptions", async () => {
  const files: Record<string, string> = {
    "sdk/parents/base/pom.xml": "<project><groupId>com.azure</groupId><artifactId>parent</artifactId><packaging>pom</packaging></project>",
    "sdk/demo/ci.yml": `extends:\n  parameters:\n    Artifacts:\n      - name: azure-core-management\n        groupId: com.azure\n      - name: spring-cloud-azure-resourcemanager\n        groupId: com.azure.spring\n      - name: azure-loadtesting\n        groupId: com.azure\n      - name: azure-core-test\n        groupId: com.azure\n`,
  };
  for (const [name, group] of [
    ["azure-core-management", "com.azure"], ["spring-cloud-azure-resourcemanager", "com.azure.spring"],
    ["azure-loadtesting", "com.azure"], ["azure-core-test", "com.azure"],
  ]) {
    files[`sdk/demo/${name}/pom.xml`] = `<project><parent><groupId>com.azure</groupId><artifactId>parent</artifactId><relativePath>../../parents/base/pom.xml</relativePath></parent><groupId>${group}</groupId><artifactId>${name}</artifactId></project>`;
  }
  files["sdk/demo/azure-loadtesting/src/main/java/Client.java"] = "class Client {}\n";
  const result = await collectJava(provider(files), context("java"));
  assert.equal(result.libraries.length, 3);
  assert.equal(result.libraries.find((library) => library.library === "com.azure:azure-core-management")?.category, "management");
  assert.equal(result.libraries.find((library) => library.library.startsWith("com.azure.spring:"))?.category, "data-plane");
  assert.equal(result.libraries.find((library) => library.library.startsWith("com.azure.spring:"))?.metrics.customRatio, null);
  assert.equal(result.excludedLibraries.find((library) => library.projectPath.includes("azure-core-test"))?.reason, "non-production-package");
});
