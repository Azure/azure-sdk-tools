const date = "2026-10-09T12:34:56.1234567Z";
function provider(files: Record<string, string>): SourceProvider {
  return { paths: Object.keys(files), async readText(path) {
    if (!(path in files)) throw new Error(`Missing test source ${path}`);
    return files[path];
  } };
}
